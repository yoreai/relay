// Every relay icon comes from the one mark below — run `bun run icons` after
// touching it. Before this existed the assets had drifted into two different
// marks (a grey/ring favicon against white/solid app icons) and every raster
// one was cropped: the lit path ran off the left edge, so its round cap was
// simply missing and no amount of rescaling could bring it back.
//
// og.png / banner.png are hand-composed artwork with type in them and are NOT
// generated here; social.png is, because it is only ever a 2:1 re-crop of og.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const PUBLIC = join(ROOT, "site", "public");
const ASSETS = join(ROOT, "assets");

// The mark is drawn on its own 0–32 grid (`4 → 26` with r=3.2 caps, i.e. ink
// from 0.8 to 29.2) and then inset as a whole, so the drawing below stays
// readable while the padding is one number in one place.
//
// SCALE leaves 7.5% clear on the left and right — the sides are the only place
// this glyph crowds, being wide and short, and the top/bottom get more air for
// free. The old app icons filled 95% of the width, but only by running off the
// left edge; 85% is the most the mark can take while actually fitting.
// TY centres the ink block rather than the lit path, which is what the composed
// artwork does and what keeps the white dot off the top edge.
const SCALE = 0.9577; // (32 - 2*2.4) / 28.4
const TX = 1.634; // 2.4 - 0.8 * SCALE
const TY = 4.03; // 16 - 12.5 * SCALE  → equal 8.8 above and below the ink

const GREEN = "#39ff14";
const WHITE = "#e5e7eb";
const BG = "#0a0a0a";

/**
 * @param {{ rounded: boolean }} opts — rounded for the browser tab, where the
 * icon is shown as-is; square for the app icons, which the OS masks itself.
 */
function markSvg({ rounded }) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">
  <!-- GENERATED by site/scripts/render-icons.mjs — edit that, not this -->
  <rect width="32" height="32"${rounded ? ' rx="7"' : ""} fill="${BG}"/>
  <g transform="translate(${TX} ${TY}) scale(${SCALE})">
    <!-- the route not taken: same weight, no colour -->
    <path d="M14 16 L20 8 H26" fill="none" stroke="${WHITE}" stroke-width="3.2"
          stroke-linecap="round" stroke-linejoin="round"/>
    <circle cx="26" cy="8" r="3" fill="${WHITE}"/>
    <!-- the chosen route -->
    <path d="M4 16 H26" fill="none" stroke="${GREEN}" stroke-width="3.4"
          stroke-linecap="round"/>
    <circle cx="4" cy="16" r="3.2" fill="${GREEN}"/>
    <circle cx="14" cy="16" r="4" fill="${GREEN}"/>
    <circle cx="26" cy="16" r="3.2" fill="${GREEN}"/>
  </g>
</svg>
`;
}

const png = (svg, size) =>
  sharp(Buffer.from(svg), { density: 384 }).resize(size, size).png().toBuffer();

async function main() {
  mkdirSync(PUBLIC, { recursive: true });
  mkdirSync(ASSETS, { recursive: true });

  const rounded = markSvg({ rounded: true });
  const square = markSvg({ rounded: false });

  writeFileSync(join(PUBLIC, "favicon.svg"), rounded);

  const targets = [
    [join(PUBLIC, "favicon-32.png"), rounded, 32],
    [join(PUBLIC, "apple-touch-icon.png"), square, 180],
    [join(PUBLIC, "icon-1024.png"), square, 1024],
    [join(ASSETS, "logo.png"), square, 1024],
  ];
  for (const [path, svg, size] of targets) {
    writeFileSync(path, await png(svg, size));
    console.log(`${size.toString().padStart(4)}px  ${path.replace(ROOT + "/", "")}`);
  }

  // social.png is og.png at 2:1. Cropping to the artwork's own centre (ink sits
  // at y 288–732 of 1024) rather than the canvas centre is what keeps the
  // wordmark whole — the old file cut the "y" off "relay".
  const og = join(PUBLIC, "og.png");
  const { height } = await sharp(og).metadata();
  const cropH = 768; // 1536 / 2
  await sharp(og)
    .extract({ left: 0, top: Math.round((288 + 732) / 2 - cropH / 2), width: 1536, height: cropH })
    .resize(1280, 640)
    .png()
    .toFile(join(ASSETS, "social.png"));
  console.log(`1280x640  assets/social.png  (re-cropped from og.png, ${height}px tall)`);
}

await main();
